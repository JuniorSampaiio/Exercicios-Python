#Aula de somas

A = float(input("Digite o primeiro numero: "))
B = float(input("Digite o segundo numero: "))

soma = A + B
subtracao = A - B
multiplicacao = A * B
divisao = A / B


print("Resultado: ")
print("Soma: ", soma)
print("Subtração: ", subtracao)
print("Multiplicação: ", multiplicacao)
print("Divisão: ", divisao)
