# Digite um numero, e para cada numero apresente o dia correspondente. 

dia = int(input("Digite um numero: "))

if dia == 1:
    print("Segunda-Feira")
elif dia == 2:
    print("Terça-Feira")
elif dia == 3:
    print("Quarta-feira")
elif dia == 4:
    print("Quinta-Feira")
else:
    print("Numero invalido, tente novamente!")
    



